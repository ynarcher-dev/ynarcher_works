import { cn } from '@ynarcher/ui'
import type { ReactNode } from 'react'

/**
 * 폼 카드 안에서 **입력 칸이 한 줄에 몇 개 서는가** — 화면이 아니라 **칸의 종류**가 정한다.
 *
 * 2026-09-09 사용자 지정으로 세운 규칙이다. 그 전에는 카드가 2열로 서고 그 안의 칸은 세로로
 * 쌓여, 수기로 채울 때 한 칸을 적고 아래로, 또 아래로 내려가야 했다 — 폼은 위에서 아래로
 * 길어지고 화면 오른쪽 절반은 비어 있었다. 칸을 가로로 세우면 한 줄을 채우고 다음 줄로
 * 내려가므로 눈과 손이 같은 방향으로 움직인다.
 *
 * **몇 개씩 세울지를 화면마다 정하지 않는 것이 요점이다.** 카드마다 판단하면 같은 성격의 칸이
 * 카드마다 다른 폭으로 서고, 그때부터 폭은 규격이 아니라 취향이 된다. 여기서 정하는 것은
 * *칸의 종류 → 폭* 하나이고, 화면은 종류만 고른다.
 *
 * | 종류 | 한 줄에 | 담기는 값 |
 * | :--- | :--- | :--- |
 * | `sm` | 4개 | 날짜·선택지·번호·연락처처럼 길이가 정해진 값 |
 * | `md` | 3개 | 이름·주소처럼 한 줄로 끝나는 글 |
 * | `lg` | 2개 | 여러 줄 서술(텍스트영역) |
 * | `full` | 1개 | 목록·태그처럼 폭 전체가 필요한 컨트롤 |
 *
 * 서술형이 2개씩인 이유는 **폼에서 폭이 미덕이 아니기 때문**이다(2026-09-06에 이미 밟은 자리다).
 * 전폭 텍스트영역은 한 줄이 어디서 끝나는지 눈이 따라가지 못한다. 반대로 셋씩 세우면 한글
 * 스무 자에서 줄이 바뀌어 문장을 쓰는 칸이 아니게 된다.
 *
 * 좁은 화면(`md` 미만)에서는 전부 한 줄에 하나씩 선다 — 그 폭에서 둘로 가르면 어느 칸도 제
 * 값을 담지 못한다.
 */
export type FieldWidth = 'sm' | 'md' | 'lg' | 'full'

/**
 * 종류 → 격자 스팬(12칸 기준).
 *
 * Tailwind는 클래스 이름을 빌드 때 훑으므로 값을 실행 중에 조립하지 않는다 — 조립하면 그
 * 클래스가 만들어지지 않아 폭이 통째로 사라진다.
 */
export const fieldWidthClass: Record<FieldWidth, string> = {
  sm: 'md:col-span-3',
  md: 'md:col-span-4',
  lg: 'md:col-span-6',
  full: 'md:col-span-12',
}

/**
 * 폼 카드 한 장의 입력 격자. 안에 서는 칸은 `Field`·`Label`의 `width`가 자기 폭을 말한다.
 *
 * 12칸인 이유는 2·3·4로 모두 나누어떨어지는 가장 작은 수이기 때문이다 — 한 줄에 둘·셋·넷을
 * 섞어 세워도 줄 끝이 맞는다.
 */
export function FieldGrid({ children, className }: { children: ReactNode; className?: string }) {
  return <div className={cn('grid grid-cols-1 gap-3 md:grid-cols-12', className)}>{children}</div>
}
