import { cn, formText } from '@ynarcher/ui'
import type { ReactNode } from 'react'

/**
 * 폼 카드 안에서 **입력 칸이 한 줄에 몇 개 서는가** — 화면이 아니라 **칸의 종류**가 정한다.
 *
 * 2026-09-09 사용자 지정으로 세운 규칙이다. 그 전에는 카드가 2열로 서고 그 안의 칸은 세로로
 * 쌓여, 수기로 채울 때 한 칸을 적고 아래로, 또 아래로 내려가야 했다 — 폼은 위에서 아래로
 * 길어지고 화면 오른쪽 절반은 비어 있었다. 칸을 가로로 세우면 한 줄을 채우고 다음 줄로
 * 내려가므로 눈과 손이 같은 방향으로 움직인다.
 *
 * **몇 개씩 세울지를 화면마다 정하지 않는 것이 요점이다.** 카드마다 판단하면 같은 성격의 칸이
 * 카드마다 다른 폭으로 서고, 그때부터 폭은 규격이 아니라 취향이 된다. 여기서 정하는 것은
 * *칸의 종류 → 폭* 하나이고, 화면은 종류만 고른다.
 *
 * | 종류 | 한 줄에 | 담기는 값 |
 * | :--- | :--- | :--- |
 * | `sm` | 4개 | 날짜·선택지·번호·연락처처럼 길이가 정해진 값 |
 * | `md` | 3개 | 이름·주소처럼 한 줄로 끝나는 글, 그리고 **짧은 나열형 서술** |
 * | `lg` | 2개 | 여러 줄 서술(텍스트영역) |
 * | `full` | 1개 | 목록·태그처럼 폭 전체가 필요한 컨트롤 |
 *
 * 문장을 적는 칸이 2개씩인 이유는 **폼에서 폭이 미덕이 아니기 때문**이다(2026-09-06에 이미 밟은
 * 자리다). 전폭 텍스트영역은 한 줄이 어디서 끝나는지 눈이 따라가지 못한다. 반대로 셋씩 세우면
 * 한글 스무 자에서 줄이 바뀌어 문장을 쓰는 칸이 아니게 된다.
 *
 * `md`에 나열이 함께 사는 이유는 **폭을 정하는 것이 칸의 종류이되, 그 종류를 가르는 것은 담기는
 * 글의 길이**이기 때문이다(2026-09-09 후속). "개발 5 · 영업 2 · 경영지원 1"은 문장이 아니라
 * 나열이라 좁아도 읽히고, 나열까지 `lg`로 두면 서술 칸이 홀수인 카드마다 마지막 하나가 홀로
 * 반 줄을 비운다 — 그 빈 자리가 폼을 세로로 늘린다.
 *
 * **목록형 입력은 이 격자가 아니라 `ItemRows`가 세운다**(머리글 한 줄 + 항목 한 줄). 거기서도
 * 열 폭은 담기는 값의 종류가 정하며, 목록 한 줄에 맞게 종류가 더 잘게 갈렸을 뿐이다.
 *
 * 좁은 화면(`md` 미만)에서는 전부 한 줄에 하나씩 선다 — 그 폭에서 둘로 가르면 어느 칸도 제
 * 값을 담지 못한다.
 *
 * **다만 기본 데이터 카드는 같은 날 저녁 `lg`(2개)로 통일했다**(2026-09-09 사용자 지정). 종류대로
 * 세우니 한 줄에 네 칸이 서서 눈이 가로로 네 번 훑어야 했고, 같은 줄에서 칸마다 여유가 달랐다.
 * 표가 말하는 종류→폭 규칙은 그대로 살아 있고 지금 폼이 그중 `lg`·`full` 둘만 쓰는 것이다 —
 * 한 줄에 몇 칸을 세울지는 여전히 화면이 아니라 여기서 고른 종류가 답한다.
 */
export type FieldWidth = 'sm' | 'md' | 'lg' | 'full'

/**
 * 종류 → 격자 스팬(12칸 기준).
 *
 * Tailwind는 클래스 이름을 빌드 때 훑으므로 값을 실행 중에 조립하지 않는다 — 조립하면 그
 * 클래스가 만들어지지 않아 폭이 통째로 사라진다.
 */
export const fieldWidthClass: Record<FieldWidth, string> = {
  sm: 'md:col-span-3',
  md: 'md:col-span-4',
  lg: 'md:col-span-6',
  full: 'md:col-span-12',
}

/**
 * 폼 카드 한 장의 입력 격자. 안에 서는 칸은 `Field`·`Label`의 `width`가 자기 폭을 말한다.
 *
 * 12칸인 이유는 2·3·4로 모두 나누어떨어지는 가장 작은 수이기 때문이다 — 한 줄에 둘·셋·넷을
 * 섞어 세워도 줄 끝이 맞는다.
 */
export function FieldGrid({ children, className }: { children: ReactNode; className?: string }) {
  return <div className={cn('grid grid-cols-1 gap-3 md:grid-cols-12', className)}>{children}</div>
}

/**
 * 적는 칸이 **한 줄에 하나씩** 서는 자리 — 라벨은 왼쪽 고정 열, 입력이 나머지 폭을 받는다.
 *
 * 2026-09-09 사용자 지정이다. 그 전에는 같은 카드가 `FieldRow`(한 행 N열)로 서서 다섯 칸이
 * 가로로 나란히 있었는데, **조회 화면이 같은 카드를 `InfoRows`로 세운다** — 라벨: 값이 한 줄씩
 * 위아래로 쌓인 모양이다. 두 화면의 줄 방향이 다르면 방금 읽은 값을 고치러 들어왔을 때 눈이
 * 자리를 다시 찾아야 한다. 조회가 세로면 편집도 세로다.
 *
 * 격자 폭(`6rem`)과 라벨 열의 존재 이유는 `InfoRows`와 같다 — 라벨 길이가 제각각이라 값의
 * 왼쪽 끝이 줄마다 어긋나면, 훑어 내려가는 눈이 매번 값의 시작점을 다시 찾는다. 그래서 라벨은
 * 고정 폭 열에 세우고 입력은 한 축에서 시작한다. **두 화면이 같은 6rem을 쓰는 것이 요점이다.**
 *
 * 라벨에 `md:pt-2`가 붙는 이유는 입력이 라벨보다 높기 때문이다(카드 밀도의 `py-2`). 그만큼
 * 내려야 라벨 글자가 입력 안 첫 줄과 같은 높이에 선다 — 텍스트영역이 자라도 첫 줄 기준은
 * 그대로다. 좁은 화면에서는 라벨이 입력 위로 올라서므로 그 보정을 걷는다.
 */
export function FieldLines({ children, className }: { children: ReactNode; className?: string }) {
  return (
    <div className={cn('grid grid-cols-1 gap-x-3 gap-y-2.5 md:grid-cols-[6rem_minmax(0,1fr)]', className)}>
      {children}
    </div>
  )
}

/**
 * `FieldLines` 안의 한 줄. `contents`로 자기 상자를 지워, 라벨과 입력이 부모 격자의 두 칸에
 * 직접 선다 — 상자를 남기면 줄마다 자기 안에서 폭을 나눠 라벨 축이 줄마다 어긋난다.
 */
export function FieldLine({ label, children }: { label: string; children: ReactNode }) {
  return (
    <div className="contents">
      <p className={cn('md:pt-2', formText.label)}>{label}</p>
      <div className="min-w-0">{children}</div>
    </div>
  )
}
