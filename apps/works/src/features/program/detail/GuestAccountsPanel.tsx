import type { GuestHostEntity } from '@/features/guest/host'
import { ParticipantPool } from '@/features/program/ParticipantPool'

/**
 * `와이앤아처 GUEST 설정` 모달의 `GUEST 계정 추가` 탭 — **명부 한 벌이 선다.**
 *
 * **자격 하위 탭을 걷었다**(2026-09-13 사용자 확정). 2026-09-05~09-08의 판단은 "자격은 표를
 * 거르는 조건이 아니라 게스트에게 **다른 화면을 여는 축**이라 필터처럼 읽히면 안 된다"였고,
 * 그래서 자격이 탭으로 섰다. 그 근거는 자격이 **명부의 필수 축**일 때만 성립한다.
 *
 * 지금은 성립하지 않는다. 계정을 세우는 자리가 `/guest-accounts` 하나로 모이면서 원장 연결이
 * **계정의 선택적 속성**이 되었고, 그래서 어느 원장에도 붙지 않은 게스트 계정이 생긴다. 자격
 * 탭 구조에서 그 계정은 **어느 탭에도 서지 못한다** — 화면이 자기가 관리하는 대상 일부를
 * 아예 보여 주지 못하는 상태이고, 탭을 하나 더 세워 메울 수도 없다(그 계정에는 자격이 없다).
 *
 * 그래서 자격은 축에서 **열**로 내려왔다(표의 `연결 원장`). 자격이 여는 화면이 다르다는 사실은
 * 그대로이며, 그 사실을 답하는 자리가 명부의 탭 줄이 아니라 계정의 값이 되었을 뿐이다.
 *
 * 이 컴포넌트가 얇아진 채로 남는 이유는 **탭이 이 아래에 다시 설 수 있기 때문**이 아니라,
 * 모달의 탭 하나가 무엇을 담는지 이름으로 말하는 자리가 있어야 하기 때문이다.
 */
export function GuestAccountsPanel({ host }: { host: GuestHostEntity }) {
  return <ParticipantPool host={host} />
}
