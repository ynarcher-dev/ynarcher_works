import type { ReactNode } from 'react'

export interface ColumnUnitProps {
  /** 단위 글자. 괄호는 이 컴포넌트가 두른다(`백만` → `(백만)`). */
  children: ReactNode
}

/**
 * 머리글에 병기하는 단위 — `약정총액 (백만)`.
 *
 * 단위가 설 수 있는 자리는 셋이고, 값에 붙이는 것(`50,000백만원`)은 언제나 탈락이다 — 세 글자가
 * 행 수만큼 반복되며 열 폭을 먹고, 숫자 뒤에 글자가 붙어 자릿수를 세로로 견주는 일도 어긋난다.
 *
 * 남는 둘 중 **머리글**을 고른 이유는 읽는 순서다(2026-09-02 사용자 지정). 표 위 단서 줄
 * (`DataTable`의 `caption`)은 머리글에서 눈을 한 번 떼야 읽히고, 금액 열이 여럿이면 그 단위가
 * 어느 열에 걸리는지도 줄 하나로는 말해 주지 못한다. 열 이름이 직접 말하면 그 물음이 생기지
 * 않는다. `caption`은 표 전체에 걸리는 다른 단서(기준일 등)를 위해 남는다.
 *
 * 크기는 머리글(14px)보다 한 단 낮은 12px에 굵기를 풀어 둔다. "한 줄 안에서 크기를 갈라 위계를
 * 만들지 않는다"의 예외이며, 근거는 단위가 **열 이름이 아니라 그 이름에 붙는 단서**라는 것이다 —
 * 같은 크기·굵기로 서면 `약정총액`과 `백만`이 두 개의 이름처럼 읽힌다.
 *
 * > [!NOTE]
 * > 머리글이 길어지면 그만큼 열 폭을 요구한다. 병기한 뒤에는 그 열이 자기 폭 안에 드는지
 * > 확인할 것 — 넘치면 고정폭 열의 머리글은 두 줄로 접힌다(`break-keep`).
 */
export function ColumnUnit({ children }: ColumnUnitProps) {
  return <span className="text-caption font-normal">({children})</span>
}
