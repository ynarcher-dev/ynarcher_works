-- M&A BUYER 원장에 연락 담당자 두 칸을 더한다 — 담당자명·이메일
--
-- 원장의 칸을 가르는 기준은 둘이고(20260907120000), 이 둘은 그중 **매번 같은 자리에서 꺼내
--   쓰는 값**에 해당한다. 목록을 좁히지도 정렬하지도 않지만, 본문에 묻히면 전화 한 통 걸려고
--   상세를 읽어 내려가야 한다 — 연락처는 찾는 값이지 훑는 값이 아니다.
--
-- 여기서 '담당자'는 **그 바이어 쪽 창구**이지 우리 쪽 관리 주체가 아니다. 이 원장의 관리
--   주체는 담당자 원장을 두지 않은 영구 공동관리(mna 쓰기 권한자 전원)이며, 그 축은 컬럼이
--   아니라 정책이 답한다. 두 뜻이 한 화면에 서지 않도록 이 원장에는 내부 담당자 칸을 두지
--   않는다 — 같은 낱말이 두 축을 가리키면 목록에서 누구를 부를지가 갈린다.
--
-- 전화번호는 두지 않는다. 이메일 하나면 닿고, 칸을 늘릴수록 대부분의 행에서 비는 자리가
--   늘어난다 — 번호가 필요한 바이어는 본문에 적는다(그 자리가 서술을 받는 자리다).
--
-- 보안 게이트(11_migration_security_gate.md) 점검:
--   - 소유 워크스페이스: mna / 데이터 등급: Personal(외부 기업 담당자의 이름·이메일).
--   - 컬럼 추가만이며 RLS·정책·트리거 변경 없음. 접근 경계는 기존 ma_buyers 정책 그대로다
--     (can_read/write_workspace('mna')), 게스트는 그 권한이 없어 막힌다.
--   - 개인정보이므로 화면은 마스킹 정책(콘텐츠 키 'mna.buyers')을 거쳐 렌더하고, 원본 열람은
--     log_sensitive_access RPC가 사유와 함께 access_logs에 적재한다(공용 SensitiveValue).
--     기본값은 이름 공개·이메일 마스킹이다(DEFAULT_MASK).
--   - 새 RPC·SECURITY DEFINER·Storage 정책 없음.
-- =====================================================================

alter table public.ma_buyers
  add column if not exists contact_name  text,
  add column if not exists contact_email text;

comment on column public.ma_buyers.contact_name is
  '바이어 쪽 연락 담당자명. 우리 쪽 관리 주체가 아니다 — 이 원장은 담당자 원장이 없는 영구 공동관리다.';
comment on column public.ma_buyers.contact_email is
  '바이어 쪽 담당자 이메일. 개인정보이므로 화면은 마스킹 정책(mna.buyers)을 거쳐 렌더한다.';
