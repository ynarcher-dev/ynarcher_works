-- =====================================================================
-- [정리] 데모 자문단 시드(e1000000-…) 하드 딜리트 + 그에 매달린 AC 멘토링 체인
--
-- 배경: 2026-07-14 시드 정리(20260714150000)는 b0000000 계열 전문가만 지웠고, 같은 데모
--   배치의 자문단 4명(e1000000 계열)은 남아 실데이터 사이에 섞여 있었다. 활동·만족도가
--   실집계로 연결되면서(20260731190000) 이들이 데모 멘토링 체인을 통해 '활동 1건 · 만족도
--   5.0'을 표시하게 되어, 목록에서 실적이 있는 전문가처럼 읽힌다.
--   지울 대상은 값이 아니라 값을 만들어 내는 데모 데이터 자체다.
--
-- 대상(고정 시드 UUID만 정확히 지정 — 실업로드 데이터는 건드리지 않는다):
--   * experts e1000000-…0001~0004 — 장현우·오세리·배준호·문가영(@advisor.com 가상 인물)
--   * program_participants a2000000-…0011~0013 — 위 3명의 MENTOR 참여 행
--   * mentoring_relationships a3000000-…0001~0003 → sessions a4000000-…0001~0004
--     → mentor_satisfaction_records a5000000-…0001~0004 / mentor_feedback_records a6000000-…0001~0003
--
-- 결정: 통상 규약(물리삭제 금지·soft delete)의 예외로, "안 쓰는 하드코딩 데모 데이터"를
--   완전 제거하려는 사용자 명시 요청에 따라 물리 삭제로 수행한다(20260714150000과 같은 판단).
-- 삭제 순서: FK(ON DELETE 기본=RESTRICT) 위반을 피하기 위해 자식→부모 순으로 지운다.
-- 보존: 데모 스타트업(51000000-…)과 그 STARTUP 참여 행(a2000000-…0001~0003)은 이번 범위가
--   아니다 — STARTUP 워크스페이스가 소유한 데이터라 별도 판단이 필요하다.
-- 보안 게이트: 데이터 DELETE 전용(신규 테이블/RPC/Storage 정책/SECURITY DEFINER 없음) → 해당 없음.
-- =====================================================================

