-- =====================================================================
-- 조직 개편 초안(DRAFT)은 동시에 한 건만 살아 있을 수 있다.
--
-- 조직 개편이 모달이던 시절(모달을 열 때마다 초안이 생기고 닫아도 남던 시절)의 초안이
-- org_versions에 12건 쌓여 있었다. 조직 관리 화면의 "설계 중인 개편 초안" 배너와 조직 개편
-- 페이지는 둘 다 "가장 최근 초안 한 건"만 다루므로, 초안 폐기를 눌러도 다음 초안이 곧바로
-- 배너에 올라와 아무리 폐기해도 배너가 사라지지 않는 것처럼 보였다.
--
-- 화면이 초안을 단수로 다루는 이상 원장도 단수를 보장해야 한다 — 화면에서만 "하나처럼"
-- 보여주면 지금처럼 원장에 쌓인 나머지가 언젠가 표면으로 올라온다.
--
-- 1) 남아 있는 옛 초안을 일괄 폐기(soft delete)한다. 물리 삭제하지 않는다.
-- 2) 살아 있는 DRAFT가 한 건을 넘지 못하도록 부분 유니크 인덱스로 강제한다.
-- =====================================================================

-- 1) 옛 초안 일괄 폐기 --------------------------------------------------------
-- 이 마이그레이션 시점 이전에 만들어진 초안만 대상으로 한다. 이후 정상 흐름에서 만들어진
-- 초안(설계 중인 실물)까지 쓸어 담지 않기 위한 경계다.
update public.org_versions
   set deleted_at = now()
 where status = 'DRAFT'
   and deleted_at is null
   and created_at < timestamptz '2026-07-29 00:00:00+09';

-- 2) 살아 있는 초안은 한 건 ---------------------------------------------------
-- 조직 개편은 전사 조직도를 통째로 갈아 끼우는 작업이라 동시에 두 벌을 설계할 자리가 없다.
-- 초안을 새로 만들려면 기존 초안을 예약 확정하거나 폐기해야 한다(화면도 같은 규칙으로 동작한다).
create unique index if not exists org_versions_single_live_draft
  on public.org_versions (status)
  where (status = 'DRAFT' and deleted_at is null);
