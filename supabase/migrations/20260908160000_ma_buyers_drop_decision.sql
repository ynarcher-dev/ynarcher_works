--   파는 쪽은 매물이라 "이 건을 진행할 것인가"가 그 레코드에 대한 우리 판단이지만, 사는 쪽은
--   인수 의향을 가진 상대라 진행 여부는 상대가 아니라 **딜마다** 갈린다 — 한 바이어가 세 건을
--   보고 둘은 접고 하나만 가는 것이 정상이고, 그 판단을 바이어 행에 하나만 적으면 어느 건에
--   대한 답인지 말할 수 없다. 딜 단위 판단이 필요해지는 날 그 자리는 ma_programs 쪽이다.
