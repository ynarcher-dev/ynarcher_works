-- **끄지 않고 지운다.** 컬럼을 남기고 화면만 감추면 원장은 "바이어도 진행여부를 갖는다"고
--   말하는데 화면에는 없어, 다음 사람이 그 어긋남을 어느 쪽으로 맞출지 매번 판단해야 한다.
--   물리 삭제 금지 원칙과 충돌하지 않는다 — 그 원칙은 업무 기록 행을 지키는 것이고, 여기서
--   없애는 것은 같은 날 만들어져 **값이 한 건도 들어가지 않은 빈 칸**이다(2026-09-03에 정형
--   모듈 7종을 끄지 않고 지운 것과 같은 판단).
--
-- 되돌리는 비용도 작다 — 추가 마이그레이션 한 줄이며 잃을 값이 없다.
