-- 20260906120000 — 신규 스타트업의 기본 구분을 '미지정 기업'(other)으로
--
-- 왜: `other`의 뜻이 바뀌었다(2026-09-06). 종전에는 어디에도 맞지 않는 기업을 담는
-- 실카테고리('기타기업')였고 자유 라벨 칸(`management_status_etc`)까지 딸려 있었으나 실제로는
-- 한 건도 쓰이지 않았고, 정작 필요한 자리는 **"아직 무엇인지 정하지 않은 기업"**이었다.
-- 그 자리가 없어 새로 등록하는 기업이 전부 발굴기업(`sourced`)으로 들어갔고, 그래서 발굴기업
-- 수가 실제보다 컸다. 화면·업로드는 이미 `other`를 명시해 넣지만, 컬럼 기본값은 "아무도 적지
-- 않으면 무엇이 되는가"에 답하는 자리라 함께 옮긴다.
--
-- 코드값(`other`)은 그대로 둔다 — 민감정보 정책 키(`startup.etc`)·알림 경로가 이 문자열로
-- 저장돼 있어 바꾸면 기존 설정이 통째로 끊긴다. 부르는 말이 달라졌을 뿐 담는 값은 그대로다
-- (구 '산업' → '분야'에서 `industry_tags` 이름을 그대로 둔 것과 같은 판단이다).
--
-- **기존 행은 건드리지 않는다.** 지금 발굴기업으로 들어와 있는 행 중 무엇이 "진짜 발굴"이고
-- 무엇이 "몰라서 발굴"인지 판정할 근거가 없다 — 사후에 추측으로 옮기면 담당자가 직접 고른
-- 값까지 함께 흔들린다. 기본값 변경은 앞으로 들어오는 행에만 적용된다.
--
-- `management_status_etc`(구 기타 자유 라벨)는 컬럼을 남긴다. 화면 입력 칸은 걷었고 저장
-- 대상에서도 뺐으므로 값이 새로 쌓이지 않으며, 전환 시점에 값이 있는 행은 0건이었다.
-- 물리 삭제 금지 원칙대로 드롭하지 않고 주석으로 은퇴를 표시한다.
--
-- 보안 게이트(11_migration_security_gate.md): 컬럼 기본값·주석만 바꾼다. 신규 테이블·정책·
-- 함수·Storage 없음, RLS 변화 없음, 노출 범위 변화 없음, 개인정보·Export·권한 변경 없음.
-- =====================================================================

alter table public.startups
  alter column management_status set default 'other';

comment on column public.startups.management_status is
  '구분 코드 4종(sourced 발굴기업 / incubated 보육기업 / invested 투자기업 / other 미지정 기업). 기본값은 other — 아직 무엇인지 정하지 않은 기업이 들어오는 칸이고, 정해지면 담당자가 옮긴다. NOT NULL이라 값이 빈 행은 없다.';

comment on column public.startups.management_status_etc is
  '[은퇴] 구 기타기업(other)의 자유 분류 라벨. other가 미지정 기업으로 바뀌며(2026-09-06) 입력 칸과 저장 경로를 걷었다. 값이 새로 쌓이지 않으며 컬럼은 옛 값 보존을 위해 남긴다.';
