-- 배경
--   구분을 나눌 때 합의·재무합의를 병렬로 두었다. "순서를 강제하면 합의자가 자리를 비운 동안
--   결재 전체가 멈춘다"가 근거였는데, 실제로 결재선을 짜 보면 합의에도 순서가 있다 —
--   실무 검토가 끝난 뒤에 부서장이 합의하고, 재무 담당이 본 뒤에 재무 책임자가 본다.
--   순서 없는 합의자 명단은 화면에서도 이름의 나열일 뿐이라 누가 먼저인지 물을 자리가 없었다.
--
-- 결정
--   세 구분 모두 **자기 줄 안에서** step_order 순으로 흐른다. 앞 순번이 처리해야 다음 차례가
--   온다. 다만 **구분끼리는 서로를 기다리지 않는다** — 결재 1번과 합의 1번은 동시에 각자의
--   차례일 수 있다. 합의 줄을 결재 줄의 앞뒤에 못 박으면 두 줄이 사실은 한 줄이 되어, 결재선
--   표가 구분을 나눠 보여 주는 뜻이 사라진다.
--
--   최종 승인·반려 규칙은 그대로다: 구분과 무관하게 모든 행이 승인돼야 문서가 승인되고,
--   어느 하나라도 반려되면 문서가 반려된다.
--
--   차례 판정은 종전과 같이 **클라이언트(model.isMyTurn)**가 하고 DB는 강제하지 않는다.
--   결재 구분의 순차도 원래 서버에서 막지 않았으므로(RLS는 "본인 행만 갱신"이라는 경계만
--   지킨다), 합의에만 새 강제를 넣으면 같은 성격의 규칙이 두 곳에서 다른 힘으로 서게 된다.
--   순번을 건너뛴 처리는 권한을 넘는 행위가 아니라 절차의 문제이므로 경계가 아니라 흐름이
--   답한다 — 서버 강제가 필요해지면 세 구분을 한꺼번에 옮긴다.
--
--   이 마이그레이션은 **주석만 고친다**(데이터·정책·구조 변경 없음). 컬럼 주석이 결재선
--   진행 규칙의 서술 원본이라, 규칙이 바뀌었는데 주석이 옛 규칙을 말하면 DB만 보고 판단하는
--   사람이 틀린 근거를 얻는다.
--
-- 보안 게이트 메모(docs/docs_dev/11_migration_security_gate.md)
