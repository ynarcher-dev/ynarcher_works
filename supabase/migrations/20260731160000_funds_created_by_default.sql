-- =====================================================================
-- FUND 원장 생성자(created_by) 자동 기록
--
-- 배경: NETWORKS 원장 13종(20260714130000)과 사업 원장 3종(20260721170000)에는
--       created_by 기본값(app.current_app_user_id())이 걸려 있는데 funds만 빠져 있었다.
--       클라이언트(useCreateFund)도 created_by를 보내지 않아 지금까지 등록된 펀드는
--       생성자가 전부 null이며, '내 펀드 관리'가 생성자 축으로는 한 건도 걸리지 않았다
--       (대표펀드매니저(manager_id)로 지정된 펀드만 보였다).
--
--       대용량 업로드(upload_insert_entities)도 컬럼을 명시하지 않은 값은 DB 기본값에
--       맡기므로, 기본값이 없으면 업로드로 들어온 펀드가 아무의 '내 펀드'에도 들어가지 않는다.
--
-- 보안 게이트(11_migration_security_gate.md):
--   - 신규 테이블/함수/정책 없음. 기존 컬럼에 default 1개 추가.
--   - 생성자는 권한 축이 아니다(funds의 어떤 정책도 created_by로 쓰기를 허용하지 않는다).
--     '내 펀드' 목록의 소속과 최초 등록 책임 표기만 바뀐다.
--   - 기존 행은 건드리지 않는다 — 실제로 누가 만들었는지 알 수 없는 값을 추정해 채우면
--     그 추정이 그대로 사실처럼 굳는다. 오귀속 정리는 ADMIN '생성자 교체'가 담당한다.
--   - 멱등: set default 반복 적용 안전.
-- =====================================================================

alter table public.funds
  alter column created_by set default app.current_app_user_id();

comment on column public.funds.created_by is
  '생성자(레코드를 만든 사람). 권한 축이 아니며 ''내 펀드 관리'' 소속과 표기에만 쓴다. 등록 시 자동 기록.';
