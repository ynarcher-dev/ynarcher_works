-- [M&A 퀵리뷰 모듈 1/2] 모듈 종류를 하나 더한다
-- 정본: docs/docs_planning/3_6_1_ma_seller_quick_review.md
--
-- 2026-09-08 사용자 지정 — "프로젝트에 M&A DB를 연동해. 연동하면 탭이 생기는 게 아니라
-- 모듈을 하나 생성하자. 모듈 '퀵리뷰'라고 하고, 워크북·희망사항만 보여주면 될 것 같은데
-- 디자인은 기존 모듈 디자인이랑 동일하게. 공개 범위는 WORKS ONLY."
--
-- **왜 탭이 아니라 모듈인가.** 종전에는 매물을 연결하면 프로젝트 상세에 SELLER·BUYER 탭이
-- 섰다. 그 자리가 어색했던 이유는 탭 줄이 답하는 물음과 달랐기 때문이다 — 그 줄은 '이
-- 프로젝트에서 무엇을 하는가'를 세우는데(워크플로우), 연결된 기업의 내용은 '무엇을 하는가'가
-- 아니라 '무엇을 놓고 하는가'다. 모듈로 내리면 그것이 워크플로우 한 칸이 되어, 검토라는
-- 일이 다른 일들과 같은 줄에서 상태·기간·담당자를 갖는다.
--
-- **종류를 새로 만드는 이유**(기존 종류를 쓰지 않는 것):
--   글쓰기·URL첨부·파일첨부는 담당자가 **내용을 적어 넣는** 그릇이다. 퀵리뷰는 적어 넣지
--   않는다 — M&A 원장(ma_sellers.quick_review·wish)이 이미 가진 값을 **비추기만** 한다.
--   같은 그릇에 담으면 그 모듈에서 고친 값이 어디에 저장되는지 화면이 답하지 못한다.
--
-- **공개 범위는 INTERNAL_ONLY**(화면 라벨 'WORKS ONLY')다. 매각 검토 문서라 밖으로 나가는
--   축이 아니고, 성격은 담당자가 고르지 않고 여기 템플릿이 박는다(2026-09-03 결정) —
--   그러면 내부 자료를 실수로 밖에 여는 선택지가 화면에 아예 없다.
--
-- **워크스페이스는 mna 하나**다. AC 사업에는 연결할 매물이 없으므로 카탈로그에서 빼 두면
--   그 워크스페이스의 '워크플로우 추가' 목록에 아예 서지 않는다.
--
-- **category는 OPERATION**이다. BASE는 어디에나 놓는 기본 3종의 자리이고, 퀵리뷰는 그
--   워크스페이스의 일을 하는 운영 모듈이다.
--
-- **프로젝트당 하나로 잠근다**(부분 유일 인덱스, OUTCOMES와 같은 방식). 이 모듈이 세우는
--   것은 '연결된 매물 전부'라 둘일 이유가 없고, 둘이면 어느 쪽이 이 프로젝트의 검토인지
--   화면이 답하지 못한다.
--
-- **title은 비운 채 만든다**(다음 마이그레이션의 자동 생성). `uq_program_modules_title`이
--   프로젝트 안에서 모듈명을 유일하게 잡고 있어, '퀵리뷰'를 박아 넣으면 담당자가 이미 그
--   이름의 글쓰기 모듈을 만들어 둔 프로젝트에서 **매물 연결 자체가 실패한다.** 이름이 비면
--   화면이 템플릿 라벨('퀵리뷰')로 폴백하므로 보이는 것은 같다.
--
-- 파일을 둘로 가르는 이유: `alter type ... add value`로 더한 값은 **같은 트랜잭션 안에서
-- 쓸 수 없다.** 그래서 이 파일에는 값을 더하는 일과, 그 값을 **문자열로만** 쓰는 카탈로그
-- 행 하나만 둔다(module_templates.key는 enum이 아니라 text다). 값을 실제로 쓰는 것 둘 —
-- 싱글턴 인덱스의 조건절과 자동 생성 RPC — 은 다음 마이그레이션이 갖는다.
--
-- 처음에는 인덱스를 여기 두었다가 55P04(unsafe use of new value)로 막혔다. 조건절의
-- `module_type = 'QUICK_REVIEW'`가 그 값을 **쓰는** 일이기 때문이다 — 값을 더하는 것과
-- 그것으로 무언가를 판정하는 것은 트랜잭션 경계를 사이에 두고 갈린다.
--
-- 보안 게이트(docs/docs_dev/11_migration_security_gate.md) 답변:
--   - 소유 워크스페이스: mna
--   - 데이터 등급: 해당 없음(카탈로그 행 하나 · enum 값 하나 — 업무 데이터가 아니다)
--   - 접근 주체: 카탈로그 읽기는 종전대로 전 내부 사용자, 쓰기는 ADMIN(정책 무변경).
--   - Scope 기준: 무변경.
--   - 신규 테이블 없음. 신규 정책 없음. 신규 RPC 없음. SECURITY DEFINER 신설 없음.
--   - 감사 로그: 해당 없음.
--   - 운영 영향: 이 파일만으로는 아무 일도 일어나지 않는다. 화면이 이 종류를 알기 전까지
--     '워크플로우 추가' 목록에 라벨 없이 서지 않도록, 프론트와 같은 커밋에서 배포한다.
-- =====================================================================

alter type public.module_type add value if not exists 'QUICK_REVIEW';

-- 카탈로그 행. `on conflict do nothing` — 시드는 초기값이지 정답이 아니며, ADMIN이 고친
-- 값을 재실행이 되돌려서는 안 된다(2026-09-02 모듈 카탈로그 결정).
insert into public.module_templates (key, category, sort_order, is_active, workspaces, visibility)
values ('QUICK_REVIEW', 'OPERATION', 10, true, array['mna']::text[], 'INTERNAL_ONLY')
on conflict (key) do nothing;
