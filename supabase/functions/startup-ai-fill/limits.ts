// [AI 작성하기] 한도 값의 단일 원천.
//
// 종전에는 14MB라는 숫자가 sources.ts·화면 문구·모달 안내 세 곳에 각각 적혀 있었다. 값을
// 올리는 날 한 곳만 고치면 화면은 "14MB를 넘습니다"라고 말하는데 서버는 통과시키는 상태가
// 되므로, 값과 그 값을 말하는 문구를 함께 여기 둔다.
//
// 근거: docs/docs_planning/3_3_5_startup_ai_fill.md §9

/**
 * 한 번에 읽을 자료의 합산 상한.
 *
 * 이 값이 인라인 한도(아래)보다 큰 것은 **보내는 방식이 둘**이기 때문이다. 합이 인라인
 * 한도 안에 들면 요청에 실어 보내고, 넘으면 Files API로 올린 뒤 주소만 참조한다.
 */
export const MAX_TOTAL_BYTES = 50 * 1024 * 1024

/** 한 건의 상한. 합산 안에 들어도 한 파일이 전부를 먹으면 나머지를 함께 읽을 수 없다. */
export const MAX_SINGLE_BYTES = 30 * 1024 * 1024

/**
 * 요청에 실어 보낼 수 있는 합계.
 *
 * 모델의 한 요청 한도는 20MB인데 자료를 문자로 바꿔 실으므로 약 1.33배로 부푼다. 프롬프트
 * 자리까지 남겨 14MB로 둔다. **이 값은 올릴 수 없다** — 올리면 요청 자체가 거절된다.
 * 여기를 넘는 자료는 인라인이 아니라 Files API로 간다.
 */
export const MAX_INLINE_BYTES = 14 * 1024 * 1024

/** 한 번에 읽을 자료 수. */
export const MAX_FILES = 5

/**
 * 링크 한 건에서 뽑아 낼 글자 수.
 *
 * 바이트 상한만으로는 부족하다 — 한글 4MB는 200만 토큰이 넘어 모델이 한 번에 읽는 양을
 * 통째로 넘긴다. 10만 자면 웬만한 보도자료·공시를 다 담고, 넘치면 앞부분만 읽고 그 사실을
 * 담당자에게 말한다(조용히 자르면 왜 부실한 초안인지 알 수 없다).
 */
export const MAX_LINK_CHARS = 100_000

/** 상한을 사람이 읽는 문구로. 숫자와 문구가 어긋나지 않게 항상 이것을 쓴다. */
export function mb(bytes: number): string {
  return `${Math.round(bytes / (1024 * 1024))}MB`
}
