/**
 * 소재지 선택지는 ADMIN 원장(location_tags)이 소유하므로 요청 시점에 받아 붙인다.
 *
 * 여기 목록을 적어 두지 않는 이유는 같은 값을 두 곳에 두지 않기 위해서다 — 원장에서 시·도가
 * 하나 늘거나 이름이 바뀌면, 적어 둔 쪽은 그날부터 화면에 없는 값을 지시하게 된다.
 */
export function basicsPrompt(locations: string[]): string {
  const list = locations.length > 0 ? locations.join(" / ") : "(목록을 불러오지 못했습니다 — 이 칸은 null로 두세요)"
  return `${BASICS_BODY}

소재지 고정 선택지: ${list}`
}

