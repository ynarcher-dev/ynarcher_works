// **기본 정보**는 이 기능에서 가장 확실한 자리다. 상호·대표자·설립일·사업자등록번호는 서류에
// 인쇄된 사실이라 해석의 여지가 없고, 담당자가 손으로 옮겨 적던 값이다. 대신 옮겨 적는
// 자리인 만큼 어느 서류를 우선할지가 전부다(등기부 > 사업자등록증).
//
// **요약**은 반대로 이 기능에서 **유일하게 판단을 요구하는 카드**다. 나머지 카드가 "문서에
// 적힌 것을 칸에 옮기는" 일이라면 요약은 "문서들을 읽고 무엇이 강점이고 무엇이 부족한지를
// 말하는" 일이다. 그래서 공통 규약의 명사구 규칙을 이 카드만 벗는다 — 관계를 말해야 하는데
// ("매출은 느는데 적자 폭도 커진다") 명사구로는 관계가 표현되지 않는다.
//
// 다만 **판단의 재료는 여전히 문서 안에만 있다.** 근거 없는 값을 쓰지 않는다는 계약은 이
// 카드에서도 그대로다. 달라지는 것은 "옮겨 적는가"이지 "지어내도 되는가"가 아니다.
//
// 근거: docs/docs_planning/3_3_5_startup_ai_fill.md §7.0

