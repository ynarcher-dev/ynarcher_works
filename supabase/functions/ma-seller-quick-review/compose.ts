function buildComposePrompt(cards: CardKey[], subject: string): string {
  // 절 순서는 요청 순서가 아니라 문서 순서다(1단계와 같은 근거 — 같은 조합이면 같은 요청이어야 한다).
  const ordered = CARD_KEYS.filter((k) => cards.includes(k))
  const names = ordered.map((k) => `${k}(${CARD_LABELS[k]})`).join(', ')
  const sections = ordered
    .map((k) => CARD_RULES[k])
    .filter((s): s is string => Boolean(s))
    .join('\n\n---\n\n')

  return [
    ROLE,
    STYLE,
    SKELETON,
    `출력 봉투:
- cards: 아래 지시가 있는 절만 키로 갖습니다. 지시하지 않은 절과, 지시에 없는 칸은 넣지 않습니다.
- notes: 절별 문자열 목록(최대 ${LIMITS.notes}줄, 한 줄 80자). 다시 쓰면서 발견한 문제 —
  절끼리 어긋난 숫자, 이 절에 맞지 않아 뺀 값 — 만 남깁니다. 잘 썼다는 말은 적지 않습니다.`,
    `매각 대상 기업: ${subject || '(사실 JSON에서 확인)'}\n다시 쓸 절: ${names}`,
    '--- 절별 지시 ---',
    sections,
  ].join('\n\n')
}

/**
 * 이 대상의 작문 패스 규격.
 *
 * 온도가 1단계(0.2)보다 높은 것은 하는 일이 다르기 때문이다. 0.2로 두면 위 골격의 이음매를
 * 그대로 베껴 기업마다 같은 문형이 나온다. 그렇다고 크게 올리지는 않는다 — 여기서 넓어져야
 * 하는 것은 표현의 폭이지 사실의 폭이 아니다.
 */
export const quickReviewCompose: ComposeSpec<CardKey, QuickReviewContext> = {
  cardSchemas: COMPOSE_SCHEMAS,
  buildPrompt: (cards, subject) => buildComposePrompt(cards, subject),
  modelEnv: 'GEMINI_COMPOSE_MODEL',
  temperature: 0.45,
}
