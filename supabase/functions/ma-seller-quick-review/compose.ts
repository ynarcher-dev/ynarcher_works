// [M&A 셀러 퀵 리뷰] 2단계 — **문장을 세우는 지시와, 다시 쓰는 칸의 규격.**
//
// 1단계(prompts.ts)가 자료에서 사실을 빠짐없이 뽑고, 여기가 그 사실만 받아 문장으로 세운다.
// 자료는 실리지 않는다 — 손에 있는 것이 확정된 값뿐이라 **지어낼 자리가 없다.**
//
// ## 왜 이 파일이 생겼나
//
// 사람이 쓴 퀵 리뷰와 생성 결과를 나란히 놓고 갈린 지점은 값이 아니라 **함의**였다. 사람이 쓴
// 문서는 줄마다 "사실 → 그래서 무엇인가"가 붙어 있다("중간 유통 단계 생략 → 마진 방어 및
// 실시간 판매 데이터 확보"). 생성 결과에는 앞부분만 있었다. 1단계 프롬프트가 "수치가 없는
// 줄은 쓰지 않는다"로 조여 두었기 때문인데, 그 규칙은 홍보문을 막으려던 것이지 함의를 막으려던
// 것이 아니었다. 한 요청에서 그 둘을 가려 지시하기는 어렵다 — 느슨하게 풀면 근거 없는 형용사가
// 돌아온다. **사실이 이미 확정된 뒤에 말하면** 함의를 허용해도 지어낼 사실이 없다.
//
// ## 다시 쓰는 칸을 고르는 기준 하나 — 문장인가
//
// 회사명·주주·연도 표·제품별 실적은 여기 오지 않는다. 값이 서는 자리라 다듬을 문장이 없고,
// 두 번째 모델을 한 번 더 통과시키면 숫자 한 자리가 바뀌어도 우리가 알 수 없다.
//
// 근거: docs/docs_planning/3_6_1_ma_seller_quick_review.md §5.7

import { arr, obj, STR, type SchemaNode } from '../_shared/aiFill/schema.ts'
