// [AI 작성하기] 한도 값의 단일 원천.
//
// 종전에는 14MB라는 숫자가 sources.ts·화면 문구·모달 안내 세 곳에 각각 적혀 있었다. 값을
// 올리는 날 한 곳만 고치면 화면은 "14MB를 넘습니다"라고 말하는데 서버는 통과시키는 상태가
// 되므로, 값과 그 값을 말하는 문구를 함께 여기 둔다.
//
// 근거: docs/docs_planning/3_3_5_startup_ai_fill.md §9

/**
 * 한 번에 읽을 자료의 합산 상한.
 *
 * 이 값이 인라인 한도(아래)보다 큰 것은 **보내는 방식이 둘**이기 때문이다. 합이 인라인
 * 한도 안에 들면 요청에 실어 보내고, 넘으면 Files API로 올린 뒤 주소만 참조한다.
 */
export const MAX_TOTAL_BYTES = 50 * 1024 * 1024

/** 한 건의 상한. 합산 안에 들어도 한 파일이 전부를 먹으면 나머지를 함께 읽을 수 없다. */
export const MAX_SINGLE_BYTES = 30 * 1024 * 1024

/**
 * 요청에 실어 보낼 수 있는 합계.
 *
 * 공급자의 현재 절대 한도가 아니라 **Edge Function의 보수적인 메모리 전환점**이다. 인라인은
 * 자료를 base64로 바꾸며 약 1.33배로 부풀고, 원본 바이트·base64·JSON 본문이 한동안 함께
 * 메모리에 선다. 여기를 넘는 자료는 Files API로 보내 256MB 런타임에서 큰 문자열 사본을
 * 만들지 않는다. 공급자 한도가 바뀌어도 이 값은 우리 실행 환경을 기준으로 다시 잰다.
 */
export const MAX_INLINE_BYTES = 14 * 1024 * 1024

/**
 * 글자 계열(텍스트·CSV·JSON·HTML…) 자료의 합산 상한.
 *
 * **바이트만으로는 부족하기 때문에 있는 두 번째 예산이다.** 같은 1MB라도 담기는 양이 형식마다
 * 다르다 — PDF 1MB는 몇십 쪽이고 이미지 1MB는 사진 한 장이지만, 한글 텍스트 1MB는 35만 자
 * (약 35만 토큰)다. 전체 예산을 글자 계열로만 채우면 모델이 한 번에 읽는 양을 통째로 넘겨,
 * 자료가 상한 안인데도 요청이 거절된다. 2MB면 한글 70만 자로 웬만한 보고서 수백 쪽이다.
 *
 * 개수 상한을 걷으면서 세운 값이다. 종전에는 "5개까지"가 이것을 우연히 막고 있었다.
 */
export const MAX_TEXT_BYTES = 2 * 1024 * 1024

/**
 * 모아 두는 조각 글자의 총량 상한 — **요청 예산이 아니라 메모리 한계선이다.**
 *
 * 예산(`MAX_TEXT_BYTES`)과 갈라 둔 이유는 둘이 재는 것이 다르기 때문이다. 예산은 *한 요청이
 * 모델에 실어 보낼 양*이라 묶음마다 다시 적용되고, 이 값은 *함수가 한동안 손에 들고 있는 양*
 * 이라 실행 전체에 한 번 적용된다. 종전에는 이 둘이 한 값이어서, 예산을 넘긴 자료는 모으는
 * 단계에서 통째로 버려졌다 — 어느 묶음이 그 자료를 실제로 필요로 하는지 알기도 전에 그랬다.
 *
 * 여기 걸릴 일은 드물다(파서가 파일당 20만 자에서 이미 끊는다). 걸리면 그 자료만 사유와 함께
 * 빠지고 나머지로 초안을 만든다.
 */
export const MAX_COLLECT_TEXT_BYTES = 8 * 1024 * 1024

/**
 * 자료를 가져오는 것부터 모델 응답까지 전부를 덮는 상한.
 *
 * 종전에는 모델 호출만 120초로 재고 자료 가져오기·업로드는 재지 않았다. 링크 다섯 건이
 * 각자 15초를 쓰면 그 앞에서만 75초가 지나가므로, 함수 자체가 죽는 것이 먼저다. 한 타이머가
 * 전부를 덮어야 담당자가 "시간이 초과됐다"는 답이라도 받는다.
 *
 * **140초에서 125초로 내렸다(2026-09-06).** 함수의 응답 상한은 150초인데 그 안에서 우리가
 * 하는 일이 타이머가 끊긴 뒤에도 남는다 — 올린 자료 지우기, 응답 직렬화다. 종전의 10초
 * 여유로는 자료가 여럿일 때 정리가 끝나기 전에 함수가 죽어, 지웠어야 할 기밀 자료가 구글에
 * 남았다. 병렬 요청으로 모델 몫이 짧아졌으므로 상한을 내려도 잃는 것이 없다.
 */
export const TIMEOUT_MS = 125_000

/**
 * 모델 요청 **한 번**에 거는 상한. 넘기면 같은 요청을 한 번 더 보낸다.
 *
 * 전체 상한과 별개로 두는 이유는 실측이 말한 것 때문이다(2026-09-11). 묶음 넷 중 셋은 15~40초에
 * 돌아오는데 **남은 하나가 95초 넘게 돌아오지 않는 일**이 실행마다 났고, 느린 묶음이 매번
 * 달랐다(재무·핵심 포인트가 번갈아). 재시도 로그도 오류 로그도 없었다 — 공급자가 응답을 그냥
 * 오래 붙들고 있는 꼬리 지연이고, 대형 문맥에서 드물지 않다.
 *
 * 그 한 건 때문에 **전체가 상한에 걸려** 이미 끝난 묶음의 문장 다듬기까지 함께 날아갔다.
 * 무작위 지연이므로 **다시 보내면 대개 정상 속도로 온다**. 자료는 컨텍스트 캐시에 있어 재요청의
 * 입력 값이 거의 들지 않는 것이 이 판단을 값싸게 만든다.
 *
 * 50초인 것은 예산이 정했다 — 자료 조립에 20초 남짓 쓰고 남는 100초 안에 **두 번**이 들어가야
 * 한다. 더 짧게 잡으면 정상적으로 긴 생성(핵심 포인트는 8,000토큰을 32초에 낸다)을 느린 것으로
 * 오인해 멀쩡한 답을 버리고 다시 묻는다.
 */
export const ATTEMPT_TIMEOUT_MS = 60_000

/**
 * 다시 보내려면 적어도 이만큼은 남아 있어야 한다.
 *
 * 남은 시간이 이보다 적을 때 다시 보내는 것은 **두 번째 시도를 실패시키려고 예산을 쓰는 일**이다.
 * 그러느니 그 묶음을 곧바로 실패로 접어야 한다 — 이미 끝난 묶음들의 문장 다듬기가 그 시간을
 * 쓸 수 있고, 담당자는 "몇 개는 됐다"는 답이라도 빨리 받는다.
 *
 * 실측이 이 칸을 만들었다(2026-09-11 두 번째): 50초 상한으로 두 번 보냈다가 둘 다 넘겨, 느린
 * 묶음 하나가 **혼자 100초를 쓰고도 실패**했고 그 바람에 멀쩡히 끝난 셋의 작문까지 날아갔다.
 */
export const MIN_RETRY_BUDGET_MS = 35_000

/**
 * 응답이 이만큼 안 오면 **같은 요청을 하나 더 보내고 먼저 오는 쪽을 쓴다**(헤지).
 *
 * 실측(2026-09-11, 실행 8회)에서 정상 응답은 9~40초에 왔고, 그 뒤로 안 오는 요청은 60초를
 * 넘겨도 안 왔다 — 느린 것이 아니라 붙들린 것이다. 그런 요청을 상한까지 기다렸다가 다시
 * 보내면 두 번째가 들어갈 시간이 남지 않는다. 옆에 하나 더 세우면 붙들린 쪽을 버리고도
 * 예산 안에 든다. 자료가 캐시에 있어 둘째 요청의 입력 값은 거의 들지 않는다.
 *
 * 30초인 것은 정상 범위의 위쪽 끝이다 — 더 이르면 멀쩡히 오고 있는 답 옆에 쓸데없는 요청을
 * 세우고, 더 늦으면 둘째가 예산에 못 든다.
 */
export const HEDGE_AFTER_MS = 30_000

/** 헤지 요청을 세우려면 적어도 이만큼은 남아 있어야 한다(새 요청 하나가 답하는 데 드는 시간). */
export const MIN_HEDGE_BUDGET_MS = 25_000

/**
 * 묶음들이 끝나야 하는 시각과 전체 상한 사이에 남겨 두는 몫 — **문장 다듬기의 자리**다.
 *
 * 남기지 않으면 묶음이 예산을 남김없이 쓰고 작문 패스는 시작하자마자 끊긴다(실측의 모든 실행이
 * `composeFailed`였던 이유다). 작문은 자료를 싣지 않아 12초 남짓이면 끝나므로 이만큼이면 된다.
 */
export const COMPOSE_RESERVE_MS = 20_000

/**
 * 자료를 모아 오는 데 쓸 수 있는 시간.
 *
 * 개수 상한이 막고 있던 나머지 하나다. 링크는 한 건마다 바깥으로 나가 최대 15초를 기다리므로
 * 크기가 작아도 건수만큼 시간을 먹는다. 전체 상한 시간에만 기대면 다 읽지도 못한 채
 * 504로 끝나 아무 결과도 남지 않으므로, 여기서 먼저 끊고 **읽은 것으로 초안을 만든다**.
 * 나머지 70초는 모델이 쓴다 — 요청이 병렬이라 묶음이 여섯이어도 가장 느린 하나가 기준이다.
 */
export const ASSEMBLY_BUDGET_MS = 55_000

/**
 * 묶음 요청을 동시에 몇 개까지 보낼 것인가.
 *
 * 조합이 여섯이면 여섯을 한꺼번에 보내고 싶지만, 같은 키로 몰리면 요율 제한(429)에 걸려
 * 오히려 전부 느려진다. 셋이면 열두 카드가 두 번의 왕복 안에 끝나고 한 번에 나가는 요청은
 * 손에 꼽는다. **요율 티어가 낮은 키에서는 `GEMINI_MAX_CONCURRENCY`로 내린다** — 시크릿
 * 변경은 재배포가 필요 없으므로 운영 중에 조일 수 있어야 한다.
 */
export const GROUP_CONCURRENCY = 3

/**
 * 자료를 동시에 몇 개까지 올릴 것인가.
 *
 * 모델 요청보다 낮게 잡을 이유가 없어 같은 값을 쓰되 이름을 따로 둔다 — 둘은 서로 다른
 * 한도에 부딪히므로(업로드는 대역폭, 생성은 요율) 한쪽을 조일 때 다른 쪽이 함께 움직이면
 * 왜 조였는지가 값에서 사라진다.
 */
// **여섯으로 올렸다(2026-09-11).** 자료 조립이 실행마다 21~27초를 먹었고 그 대부분이 파일을
// 셋씩 올리고 처리 완료를 기다리는 왕복이었다. 전체 상한이 고정된 자리라 여기서 아낀 초가
// 그대로 모델의 몫이 된다.
export const UPLOAD_CONCURRENCY = 6

/**
 * 올린 자료를 지우는 요청 하나의 상한.
 *
 * 지우는 일이 응답을 붙잡아서는 안 된다. 이미 만들어진 초안이 손에 있는데 정리가 늦어져
 * 담당자가 504를 받으면, 지우기의 목적(자료를 오래 남기지 않는다)을 지키려다 그 초안을 잃는다.
 * 시간을 넘긴 지우기는 구글의 48시간 자동 삭제가 뒤를 받친다.
 */
export const DELETE_TIMEOUT_MS = 5_000

/**
 * 링크 한 건에서 뽑아 낼 글자 수.
 *
 * 바이트 상한만으로는 부족하다 — 한글 4MB는 200만 토큰이 넘어 모델이 한 번에 읽는 양을
 * 통째로 넘긴다. 10만 자면 웬만한 보도자료·공시를 다 담고, 넘치면 앞부분만 읽고 그 사실을
 * 담당자에게 말한다(조용히 자르면 왜 부실한 초안인지 알 수 없다).
 */
export const MAX_LINK_CHARS = 100_000

/** 상한을 사람이 읽는 문구로. 숫자와 문구가 어긋나지 않게 항상 이것을 쓴다. */
export function mb(bytes: number): string {
  return `${Math.round(bytes / (1024 * 1024))}MB`
}
